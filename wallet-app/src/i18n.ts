const dictionaries: Record<Lang, Record<string, string>> = { en, 'zh-Hant': zhHant, 'zh-Hans': zhHans }

let lang: Lang = 'en'
let overrides: Record<string, string> = {}

export function setLang(next: Lang): void {
  lang = next
  try {
    localStorage.setItem('scdoapp_lang', next)
  } catch {
    /* private mode */
  }
  document.documentElement.lang = next === 'en' ? 'en' : next === 'zh-Hant' ? 'zh-Hant' : 'zh-Hans'
}

export function getLang(): Lang {
  return lang
}

export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('scdoapp_lang')
    if (saved === 'en' || saved === 'zh-Hant' || saved === 'zh-Hans') return saved
  } catch {
    /* ignore */
  }
  const n = (navigator.language || 'en').toLowerCase()
  if (n.startsWith('zh')) {
    if (n.includes('cn') || n.includes('sg') || n.includes('hans')) return 'zh-Hans'
    return 'zh-Hant'
  }
  return 'en'
}

export function setStringOverrides(table: Record<string, string> | undefined): void {
  overrides = table || {}
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const raw = overrides[key] || dictionaries[lang][key] || dictionaries.en[key] || key
  if (!vars) return raw
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => (vars[k] == null ? '' : String(vars[k])))
}

export function dictionary(which: Lang = 'en'): Record<string, string> {
  return dictionaries[which]
}
